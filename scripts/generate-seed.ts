// Writes db/seed.sql from the demo catalogue (src/lib/demo/data.ts), so a fresh
// database starts with exactly the content you see in demo mode.
// Run: npx tsx scripts/generate-seed.ts
import { writeFileSync } from 'node:fs'
import { demoRows } from '../src/lib/demo/data'

// Columns that exist in the database for each table (see db/migrations).
const COLUMNS: Record<string, string[]> = {
  categories: ['id', 'parent_id', 'name', 'slug', 'description', 'image', 'banner', 'sort_order', 'show_in_menu', 'is_visible', 'seo_title', 'seo_description'],
  materials: ['id', 'name', 'slug', 'sort_order'],
  collections: ['id', 'name', 'slug', 'description', 'image', 'is_visible', 'sort_order', 'seo_title', 'seo_description'],
  products: [
    'id', 'name', 'slug', 'sku', 'category_id', 'short_description', 'description_html', 'price', 'sale_price',
    'price_on_request', 'stock_status', 'lead_time', 'images', 'options', 'specifications', 'care_html', 'delivery_html',
    'material_ids', 'collection_ids', 'related_ids', 'tags', 'is_best_seller', 'is_new_arrival', 'is_featured',
    'is_visible', 'sort_order', 'seo_title', 'seo_description', 'published_at', 'created_at', 'updated_at',
  ],
  offers: ['id', 'name', 'badge', 'discount_type', 'discount_value', 'scope', 'category_ids', 'collection_ids', 'product_ids', 'starts_at', 'ends_at', 'is_active', 'priority'],
  announcements: ['id', 'message', 'link_url', 'is_active', 'starts_at', 'ends_at', 'sort_order'],
  hero_slides: ['id', 'eyebrow', 'heading', 'subheading', 'button_label', 'button_url', 'desktop_image', 'mobile_image', 'text_align', 'text_tone', 'overlay', 'is_active', 'starts_at', 'ends_at', 'sort_order'],
  promo_banners: ['id', 'placement', 'layout', 'eyebrow', 'heading', 'body', 'button_label', 'button_url', 'desktop_image', 'mobile_image', 'offer_id', 'is_active', 'starts_at', 'ends_at', 'sort_order'],
  home_sections: ['id', 'type', 'eyebrow', 'title', 'subtitle', 'is_visible', 'sort_order', 'settings'],
  reviews: ['id', 'product_id', 'customer_name', 'city', 'rating', 'title', 'body', 'source', 'status', 'is_featured', 'review_date', 'created_at'],
  pages: ['id', 'slug', 'title', 'intro', 'body_html', 'blocks', 'hero_image', 'seo_title', 'seo_description'],
  faqs: ['id', 'question', 'answer_html', 'group_name', 'sort_order', 'is_visible', 'show_on_customize'],
}

const SETTINGS_COLUMNS = [
  'brand_name', 'tagline', 'whatsapp_number', 'whatsapp_order_template', 'whatsapp_general_message',
  'whatsapp_custom_message', 'whatsapp_reply_note', 'phone', 'email', 'address', 'city', 'map_embed_url',
  'map_link_url', 'business_hours', 'facebook_url', 'instagram_url', 'tiktok_url', 'youtube_url',
  'default_seo_title', 'default_seo_description', 'default_delivery_html', 'default_care_html',
  'search_synonyms', 'popular_searches', 'intro_enabled',
]

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`

function insert(table: string, rows: object[]): string {
  const cols = COLUMNS[table]!
  const picked = rows.map((r) => Object.fromEntries(cols.map((c) => [c, (r as Record<string, unknown>)[c] ?? null])))
  const json = JSON.stringify(picked)
  const list = cols.join(', ')
  return `insert into public.${table} (${list})\nselect ${list} from jsonb_populate_recordset(null::public.${table}, ${lit(json)}::jsonb)\non conflict (id) do nothing;\n`
}

// Parents before children so the parent_id foreign key is satisfied.
const categories = [...demoRows.categories].sort((a, b) => Number(Boolean(a.parent_id)) - Number(Boolean(b.parent_id)))

const settings = demoRows.settings as unknown as Record<string, unknown>
const settingsJson = JSON.stringify(Object.fromEntries(SETTINGS_COLUMNS.map((c) => [c, settings[c] ?? null])))

const parts = [
  '-- Generated by scripts/generate-seed.ts from the demo catalogue. Do not edit by hand.',
  '-- Demo photography lives in /public/demo; replace images from the admin panel.',
  '',
  `update public.site_settings s set (${SETTINGS_COLUMNS.join(', ')}) = (select ${SETTINGS_COLUMNS.map((c) => `r.${c}`).join(', ')} from jsonb_populate_record(null::public.site_settings, ${lit(settingsJson)}::jsonb) r) where s.id = 1;`,
  '',
  insert('categories', categories),
  insert('materials', demoRows.materials),
  insert('collections', demoRows.collections),
  insert('products', demoRows.products),
  `insert into public.product_stats (product_id, order_clicks)\nselect (x->>'id')::uuid, (x->>'order_clicks')::int from jsonb_array_elements(${lit(
    JSON.stringify(demoRows.products.map((p) => ({ id: p.id, order_clicks: p.order_clicks }))),
  )}::jsonb) x\non conflict (product_id) do nothing;\n`,
  insert('offers', demoRows.offers),
  insert('announcements', demoRows.announcements),
  insert('hero_slides', demoRows.hero_slides),
  insert('promo_banners', demoRows.promo_banners),
  insert('home_sections', demoRows.home_sections),
  insert('reviews', demoRows.reviews),
  insert('pages', demoRows.pages),
  insert('faqs', demoRows.faqs),
]

writeFileSync('db/seed.sql', parts.join('\n'))
console.log('wrote db/seed.sql')
