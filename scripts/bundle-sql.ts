// Joins all migrations and the seed into db/setup.sql, so a new Neon database can be set up
// by pasting one file into the Neon SQL Editor (or with `npm run db:setup`).
// Run after changing a migration or the seed.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

export function bundleSql(): string {
  const dir = 'db/migrations'
  const parts = readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((f) => `-- ===== ${f} =====\n\n${readFileSync(`${dir}/${f}`, 'utf8').trim()}\n`)
  parts.push(`-- ===== seed.sql (starter content, edit or delete it in the admin) =====\n\n${readFileSync('db/seed.sql', 'utf8').trim()}\n`)
  return [
    '-- Looma Comfort: complete database setup (generated by `npm run db:bundle`, do not edit by hand).',
    '-- Paste this whole file into Neon > SQL Editor on a NEW database and press Run, once.',
    '',
    ...parts,
  ].join('\n')
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync('db/setup.sql', bundleSql())
  console.log('wrote db/setup.sql')
}
