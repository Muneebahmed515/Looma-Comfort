// Joins all migrations and the seed into supabase/setup.sql, so a new Supabase project can be
// set up by pasting one file into the SQL Editor. Run after changing a migration or the seed.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

export function bundleSql(): string {
  const dir = 'supabase/migrations'
  const parts = readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((f) => `-- ===== ${f} =====\n\n${readFileSync(`${dir}/${f}`, 'utf8').trim()}\n`)
  parts.push(
    `-- ===== seed.sql (starter content, edit or delete it in the admin) =====\n\n${readFileSync('supabase/seed.sql', 'utf8').trim()}\n`,
  )
  return [
    '-- Looma Comfort: complete database setup (generated by `npm run db:bundle`, do not edit by hand).',
    '-- Paste this whole file into Supabase > SQL Editor on a NEW project and press Run, once.',
    '',
    ...parts,
  ].join('\n')
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync('supabase/setup.sql', bundleSql())
  console.log('wrote supabase/setup.sql')
}
